function parseStationSize(size?: string) {
  const [width, depth, height] = String(size ?? "1x1x1")
    .split("x")
    .map((part) => Math.max(1, Math.floor(Number(part) || 1)));
  return { width, depth, height };
}

function stationItemDefinition(station: HarthmereCraftingStationDefinition) {
  return item(station.stationId, station.displayName, {
    maxStackSize: 20,
    baseValue: 65,
    isCraftingMaterial: false,
    category: "crafting station",
    objectMetadata: {
      objectKind: "station",
      physicalForm: "crafting_station",
      sizeVoxels: parseStationSize(station.size),
      sizeLabel: station.size ?? "1x1x1",
      craftingRoles: [
        `${station.displayName} recipes`,
        station.supportsHandcraft ? "handcraft support" : "station crafting",
      ],
      businessUse: ["home workshop", "licensed business workshop"],
      handling: ["place on owned home or business property"],
      visualDescription: `${station.displayName} crafting station`,
      procedural: {
        canGenerateWithVoxels: true,
        suggestedShape: "functional crafting station",
        palette: ["warm wood", "dark metal", "tool accents"],
        emission:
          station.stationId === HARTHMERE_CRAFTING_STATIONS.thermoblaster
            ? "contained furnace glow"
            : "none",
      },
    },
  });
}

