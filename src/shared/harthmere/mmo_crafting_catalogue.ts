let registered = false;

export function ensureHarthmereProductionCraftingCatalogue() {
  if (registered) return;
  registered = true;
  for (const station of STATIONS) {
    if (!getHarthmereCraftingStation(station.stationId)) {
      registerHarthmereCraftingStation(station);
    }
  }
  for (const tool of TOOLS) {
    if (!getHarthmereCraftingTool(tool.itemId)) {
      registerHarthmereCraftingTool(tool);
    }
    registerHarthmereItemDefinition(
      item(tool.itemId, tool.displayName, {
        maxStackSize: 1,
        // Greater-impact tools cost more: price scales with tier and the
        // tool's damage/repair power (HARTHMERE_TOOL_POWER).
        baseValue: harthmereToolBaseValueForTier(
          tool.tier,
          tool.damage ?? tool.repairPower ?? tool.cleanupPower ?? 0
        ),
        isCraftingMaterial: false,
        category: "tool",
        durabilityMax: tool.durabilityMax,
        stats: {
          toolTier: tool.tier ?? 1,
          ...(tool.damage !== undefined ? { damage: tool.damage } : {}),
          ...(tool.repairPower !== undefined
            ? { repairPower: tool.repairPower }
            : {}),
          ...(tool.cleanupPower !== undefined
            ? { cleanupPower: tool.cleanupPower }
            : {}),
        },
      })
    );
  }
  for (const def of ITEMS) {
    registerHarthmereItemDefinition(def);
  }
  for (const recipe of RECIPES) {
    if (!getHarthmereCraftingRecipe(recipe.recipeId)) {
      registerHarthmereCraftingRecipe(recipe);
    }
  }
  // HARTHMERE_FARM_TOOLS_OBTAINABLE: the core farming tools (hoe, watering can,
  // bucket) are registered as tool items above; here we make them CRAFTABLE so
  // they're never a dead end (the watering can in particular is required to water
  // home gardens). They're also sold at the Orchard Produce Stand (see the vendor
  // catalog) — craft is cheaper, buying is faster.
  for (const toolRecipe of HARTHMERE_FARMING_TOOL_RECIPES) {
    if (!getHarthmereCraftingRecipe(toolRecipe.recipeId)) {
      registerHarthmereCraftingRecipe(toolRecipe);
    }
  }
  // HARTHMERE_SPECIALIZED_BLOCKS: register the specialized-block stations,
  // block items, craft recipes, and vendor entries. Safe against the circular
  // import: `registered` above is set before any work, so the re-entrant
  // ensureHarthmereProductionCraftingCatalogue() inside this call returns
  // immediately.
  ensureHarthmereSpecializedBlocksCatalogue();
  // HARTHMERE_PLACEABLE_DECOR: register placeable furniture/decor/station item
  // defs, craft recipes, and vendor entries. Same circular-import safety as above
  // (`registered` is already true, so the re-entrant ensure call no-ops).
  ensureHarthmerePlaceableDecorCatalogue();
  // HARTHMERE_BUSINESS_STOREFRONT_GOODS: give each of the 19 businesses a
  // themed storefront (5 blocks + 4 interior items) as unlimited-stock vendor
  // entries keyed by business type, so they're buyable forever as players arrive.
  ensureHarthmereBusinessStorefrontGoods();
}

export function harthmereProductionCraftingRecipeIds() {
  ensureHarthmereProductionCraftingCatalogue();
  return RECIPES.map((recipe) => recipe.recipeId);
}
