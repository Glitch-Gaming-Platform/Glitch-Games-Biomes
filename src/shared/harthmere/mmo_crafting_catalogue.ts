function exoticBlockMetadata(
  input: Omit<
    ItemObjectMetadata,
    "objectKind" | "physicalForm" | "sizeVoxels" | "sizeLabel" | "procedural"
  >
): ItemObjectMetadata {
  return {
    objectKind: "material",
    physicalForm: "block",
    sizeVoxels: { width: 1, depth: 1, height: 1 },
    sizeLabel: "1x1x1 voxel crafting block",
    procedural: {
      canGenerateWithVoxels: true,
      suggestedShape: "single block with animated inner glow",
      palette: input.colors ?? [],
      emission: "soft contained pulse",
    },
    ...input,
  };
}

function exoticItemMetadata(
  input: Omit<ItemObjectMetadata, "sizeLabel" | "procedural">
): ItemObjectMetadata {
  return {
    sizeLabel: "handheld inventory item",
    procedural: {
      canGenerateWithVoxels: true,
      suggestedShape: input.physicalForm.replace(/_/g, " "),
      palette: input.colors ?? [],
      emission: input.energySource ? "small status glow" : "none",
    },
    ...input,
  };
}

