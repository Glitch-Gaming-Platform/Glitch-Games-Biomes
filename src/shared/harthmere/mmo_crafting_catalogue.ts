function item(
  itemId: string,
  displayName: string,
  overrides: Partial<HarthmereItemDefinition> = {}
): HarthmereItemDefinition {
  const isMaterial =
    overrides.isCraftingMaterial ??
    /(ore|ingot|wood|log|plank|hide|leather|cloth|herb|extract|dust|coal|flux|fiber|scrap|crystal|reagent|bronze|trace|seed|flour|lure|kit|shard|block|matter|fuel|filter|coolant|core|capsule|cell)/i.test(
      itemId
    );
  return {
    itemId,
    displayName,
    maxStackSize: isMaterial ? 9999 : 20,
    baseValue: 1,
    binding: "none",
    isQuestItem: false,
    isCurrency: false,
    isConsumable: false,
    isCraftingMaterial: isMaterial,
    isSpellTome: false,
    levelRequirement: 1,
    classRestriction: [],
    stats: {},
    tradeable: true,
    ...overrides,
  };
}

