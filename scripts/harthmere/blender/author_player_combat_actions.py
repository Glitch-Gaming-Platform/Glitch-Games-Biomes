def force_object_mode() -> None:
    if bpy.context.object and bpy.context.object.mode != "OBJECT":
        bpy.ops.object.mode_set(mode="OBJECT")


def armature():
    force_object_mode()
    rigs = [obj for obj in bpy.data.objects if obj.type == "ARMATURE"]
    if len(rigs) != 1:
        raise RuntimeError(f"Expected one player armature, found {len(rigs)}")
    rig = rigs[0]
    rig.animation_data_create()
    rig.animation_data.use_nla = False
    if rig.animation_data.use_tweak_mode:
        rig.animation_data.use_tweak_mode = False
    return rig


def additive_pose(base, offsets):
    pose = copy.deepcopy(base)
    for bone, offset in offsets.items():
        value = pose.get(bone, (0.0, 0.0, 0.0))
        pose[bone] = tuple(value[axis] + offset[axis] for axis in range(3))
    return pose


def additive_locations(base, offsets):
    return additive_pose(base, offsets)


def scaled_pose(pose, amount):
    return {
        bone: tuple(component * amount for component in rotation)
        for bone, rotation in pose.items()
    }


def blend_pose(a, b, amount):
    bones = set(a) | set(b)
    return {
        bone: tuple(
            (a.get(bone, (0.0, 0.0, 0.0))[axis] * (1.0 - amount))
            + (b.get(bone, (0.0, 0.0, 0.0))[axis] * amount)
            for axis in range(3)
        )
        for bone in bones
    }


