def attack_locations(style: str, heavy: bool):
    lateral = -1.0 if style in {"backhand", "rising", "sweep", "crusher", "uppercut"} else 1.0
    forward = 0.08 if heavy else 0.05
    return {
        "windup": {"Chest": (-forward * 0.25, 0.0, -0.06 * lateral), "Waist": (-forward * 0.12, 0.0, 0.03 * lateral)},
        "contact": {"Chest": (forward, 0.0, 0.08 * lateral), "Waist": (forward * 0.45, 0.0, -0.04 * lateral)},
        "follow": {"Chest": (forward * 1.25, 0.0, 0.11 * lateral), "Waist": (forward * 0.60, 0.0, -0.06 * lateral)},
    }


def create_attack(rig, name, style, heavy, base_pose, base_locations):
    windup, contact, follow = attack_key_poses(style)
    locations = attack_locations(style, heavy)

    def pose(offsets):
        return additive_pose(base_pose, offsets)

    def location(offsets):
        return additive_locations(base_locations, offsets)

    if heavy:
        frames = [
            (0.0, base_pose, base_locations),
            (2.0, pose(scaled_pose(windup, 0.30)), location(scaled_pose(locations["windup"], 0.30))),
            (5.5, pose(windup), location(locations["windup"])),
            (7.0, pose(blend_pose(windup, contact, 0.20)), location(blend_pose(locations["windup"], locations["contact"], 0.20))),
            (8.8, pose(blend_pose(windup, contact, 0.70)), location(blend_pose(locations["windup"], locations["contact"], 0.70))),
            (HEAVY_IMPACT, pose(contact), location(locations["contact"])),
            (HEAVY_IMPACT + 0.8, pose(contact), location(locations["contact"])),
            (14.0, pose(follow), location(locations["follow"])),
            (17.0, pose(blend_pose(follow, contact, -0.08)), location(locations["follow"])),
            (21.0, pose(scaled_pose(follow, 0.42)), location(scaled_pose(locations["follow"], 0.42))),
            (24.0, pose(scaled_pose(follow, 0.10)), location(scaled_pose(locations["follow"], 0.10))),
            (HEAVY_END, base_pose, base_locations),
        ]
    else:
        frames = [
            (0.0, base_pose, base_locations),
            (1.25, pose(scaled_pose(windup, 0.30)), location(scaled_pose(locations["windup"], 0.30))),
            (3.25, pose(windup), location(locations["windup"])),
            (4.15, pose(blend_pose(windup, contact, 0.22)), location(blend_pose(locations["windup"], locations["contact"], 0.22))),
            (5.2, pose(blend_pose(windup, contact, 0.72)), location(blend_pose(locations["windup"], locations["contact"], 0.72))),
            (BASIC_IMPACT, pose(contact), location(locations["contact"])),
            (BASIC_IMPACT + 0.6, pose(contact), location(locations["contact"])),
            (8.5, pose(follow), location(locations["follow"])),
            (10.5, pose(blend_pose(follow, contact, -0.06)), location(locations["follow"])),
            (13.5, pose(scaled_pose(follow, 0.40)), location(scaled_pose(locations["follow"], 0.40))),
            (15.5, pose(scaled_pose(follow, 0.10)), location(scaled_pose(locations["follow"], 0.10))),
            (BASIC_END, base_pose, base_locations),
        ]

    action = create_action(rig, name, frames)
    action["harthmereCombatProfile"] = "aaa-voxel-sword-v2"
    action["impactSeconds"] = HEAVY_IMPACT_SECONDS if heavy else BASIC_IMPACT_SECONDS
    action["durationSeconds"] = HEAVY_DURATION_SECONDS if heavy else BASIC_DURATION_SECONDS
    action["attackStyle"] = style
    action["gameplayRootMotion"] = True
    action["authoredFootwork"] = True
    action["weaponArcMotionPathReviewed"] = True
    return action


def action_fcurves(action):
    legacy = getattr(action, "fcurves", None)
    if legacy is not None:
        return list(legacy)
    curves = []
    for layer in getattr(action, "layers", []) or []:
        for strip in getattr(layer, "strips", []) or []:
            for bag in getattr(strip, "channelbags", []) or []:
                curves.extend(bag.fcurves)
    return curves


def polish_curves(action):
    for curve in action_fcurves(action):
        for key in curve.keyframe_points:
            key.interpolation = "BEZIER"
            key.handle_left_type = "AUTO_CLAMPED"
            key.handle_right_type = "AUTO_CLAMPED"


def metadata():
    result = {}
    for heavy, names, specs in ((False, BASIC_NAMES, BASIC_SPECS), (True, HEAVY_NAMES, HEAVY_SPECS)):
        for name, (style, label, arc) in zip(names, specs):
            impact = HEAVY_IMPACT_SECONDS if heavy else BASIC_IMPACT_SECONDS
            duration = HEAVY_DURATION_SECONDS if heavy else BASIC_DURATION_SECONDS
            anticipation_end = (5.5 if heavy else 3.25) / FPS
            impact_end = (HEAVY_IMPACT + 0.8 if heavy else BASIC_IMPACT + 0.6) / FPS
            follow_end = (17.0 if heavy else 10.5) / FPS
            result[name] = {
                "harthmereCombatProfile": "aaa-voxel-sword-v2",
                "family": "heavy" if heavy else "basic",
                "direction": label,
                "weaponArc": arc,
                "attackStyle": style,
                "impactSeconds": impact,
                "durationSeconds": duration,
                "fps": FPS,
                "gameplayRootMotion": True,
                "authoredFootwork": True,
                "impactHoldFrames": 0.8 if heavy else 0.6,
                "phases": [
                    {"name": "anticipation", "start": 0.0, "end": anticipation_end},
                    {"name": "strike", "start": anticipation_end, "end": impact},
                    {"name": "impact", "start": impact, "end": impact_end},
                    {"name": "followThrough", "start": impact_end, "end": follow_end},
                    {"name": "recovery", "start": follow_end, "end": duration},
                ],
            }
    result[ALIGNED_NAMES[0]] = {**result[BASIC_NAMES[0]], "alignedFallbackOf": BASIC_NAMES[0]}
    result[ALIGNED_NAMES[1]] = {**result[HEAVY_NAMES[0]], "alignedFallbackOf": HEAVY_NAMES[0]}
    return result


def main() -> None:
    options = args()
    rig = armature()
    bpy.context.scene.render.fps = FPS
    bpy.context.scene.frame_start = 0
    bpy.context.scene.frame_end = int(HEAVY_END)

    idle = bpy.data.actions.get("Idle")
    if idle is None:
        raise RuntimeError("Canonical Idle action is required as the combat-ready base pose")
    rig.animation_data.action = idle
    bpy.context.scene.frame_set(0)
    bpy.context.view_layer.update()
    base_pose = {
        bone.name: tuple(bone.rotation_quaternion.to_euler("XYZ"))
        for bone in rig.pose.bones
    }
    base_locations = {bone.name: tuple(bone.location) for bone in rig.pose.bones}

    created = []
    for heavy, names, specs in ((False, BASIC_NAMES, BASIC_SPECS), (True, HEAVY_NAMES, HEAVY_SPECS)):
        for name, (style, _, _) in zip(names, specs):
            action = create_attack(rig, name, style, heavy, base_pose, base_locations)
            polish_curves(action)
            created.append(name)

    # Keep the aligned names as deliberate compatibility fallbacks, but make
    # them authored copies of the new right-to-left attacks rather than stale
    # clones of legacy Attack / Attack2.
    for aligned, source in zip(ALIGNED_NAMES, (BASIC_NAMES[0], HEAVY_NAMES[0])):
        old = bpy.data.actions.get(aligned)
        if old is not None:
            bpy.data.actions.remove(old)
        copied = bpy.data.actions[source].copy()
        copied.name = aligned
        copied.use_fake_user = True
        created.append(aligned)

    force_object_mode()
    bpy.ops.wm.save_as_mainfile(filepath=bpy.data.filepath)
    if options.gltf:
        export_and_merge(os.path.abspath(options.gltf), ACTION_NAMES, metadata())
    print("PLAYER_COMBAT_ACTIONS_UPDATED", os.path.basename(bpy.data.filepath), ",".join(created))


if __name__ == "__main__":
    main()
