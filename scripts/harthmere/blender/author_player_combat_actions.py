#!/usr/bin/env python3
"""Author the canonical player sword-combat actions in Blender.

The actions are intentionally authored on the stock 16-bone Biomes player
armature.  They keep gameplay translation in the engine, but include planted
footwork, hip/chest counter-rotation, anticipation, a one-frame impact hold,
weapon overshoot, and staggered recovery.  The exported glTF merge preserves
every unrelated animation and all existing animation metadata.

Run with either canonical authoring blend open::

    blender --background character-animations.blend \
      --python scripts/harthmere/blender/author_player_combat_actions.py \
      -- --gltf src/galois/data/animations/character-animations.gltf

The ``_24`` / ``_30`` suffixes are retained as runtime compatibility names.
The clips are intentionally compact enough to chain: light contact lands on
frame 6 and heavy contact lands on frame 10.  Recovery remains visible when a
player stops attacking, while a buffered follow-up can cross-fade immediately
into the next direction without a dead pause.
"""

