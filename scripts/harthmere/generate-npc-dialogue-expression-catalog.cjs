#!/usr/bin/env node

require("ts-node/register/transpile-only");
require("tsconfig-paths/register");

const fs = require("fs");
const path = require("path");
const prettier = require("prettier");
const {
  buildHarthmereDialogueExpressionRecords,
} = require("../../src/shared/harthmere/npc_dialogue_expression_authoring");

const repoRoot = path.resolve(__dirname, "../..");
const outputPath = path.join(
  repoRoot,
  "src/shared/harthmere/generated/npc_dialogue_expression_catalog.ts"
);
async function main() {
  const records = buildHarthmereDialogueExpressionRecords();
  const content = `// Generated by scripts/harthmere/generate-npc-dialogue-expression-catalog.cjs
// Do not edit by hand. Update npc_dialogue_expression_plan.ts,
// native_quest_dialogue_expression_plan.ts, or the authored dialogue source,
// then rerun the generator.

import type { HarthmereDialogueExpressionRecord } from "@/shared/harthmere/npc_dialogue_expression_types";

export const HARTHMERE_DIALOGUE_EXPRESSION_RECORDS = ${JSON.stringify(
    records,
    null,
    2
  )} as const satisfies readonly HarthmereDialogueExpressionRecord[];
`;

  fs.writeFileSync(
    outputPath,
    await prettier.format(content, { parser: "typescript" })
  );
  console.log(
    `Wrote ${records.length} dialogue expression records to ${outputPath}`
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
