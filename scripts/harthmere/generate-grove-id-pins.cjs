#!/usr/bin/env node
// GENERATE_GROVE_ID_PINS
//
// Extracts every already-issued Grove quest/step/unlock id from
// `harthmere_native_quest_manifest.ts` and emits a frozen pin table.
//
// WHY A PIN TABLE AND NOT JUST DERIVED IDS
// ----------------------------------------
// Grove ids are already written into live players' `Challenges` and
// `TriggerState`. Re-deriving them would silently orphan every in-flight
// player's onboarding — the exact failure the manifest's own header comment
// warns about ("renaming a quest/objective requires an explicit migration
// instead of silently orphaning Challenges/TriggerState").
//
// Grove step pins are keyed BY INDEX (`grove:<questId>:objective:<n>`), not by
// an authored objective id, because the retired shape had no per-objective
// ids at all — objectives were bare strings in a positional array. Position is
// therefore identity here, which is why the generated modules carry an
// explicit `index` on every step and why reordering is a migration.
//
// So: derived ids are the rule for anything NEW, and this table pins
// everything that already exists. `grove_quest_ids.test.ts` asserts every
// authored quest resolves to its pin, so a future edit cannot quietly move an
// id that a player is standing on.
//
//   node scripts/harthmere/generate-grove-id-pins.cjs

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "../..");
const MANIFEST = path.join(
  ROOT,
  "src/shared/harthmere/harthmere_native_quest_manifest.ts"
);
const OUT = path.join(ROOT, "src/shared/harthmere/grove/grove_quest_id_pins.ts");

function readPins() {
  // Long keys wrap onto the following line in the manifest, so collapse
  // whitespace before matching rather than reading line by line.
  const text = fs.readFileSync(MANIFEST, "utf8").replace(/\s*\n\s*/g, " ");
  const pins = new Map();
  const pattern = /"grove:([^"]+)":\s*id\((\d+)\)/g;
  let match;
  while ((match = pattern.exec(text))) {
    pins.set(match[1], match[2]);
  }
  return pins;
}

function main() {
  const pins = readPins();
  const quest = [];
  const step = [];
  for (const [key, value] of [...pins.entries()].sort(([a], [b]) =>
    a.localeCompare(b)
  )) {
    (key.includes(":") ? step : quest).push([key, value]);
  }

  const render = (rows) =>
    rows.map(([key, value]) => `  "${key}": ${value},`).join("\n");

  fs.writeFileSync(
    OUT,
    `// GROVE_QUEST_ID_PINS — generated by
// scripts/harthmere/generate-grove-id-pins.cjs
//
// Every Grove id that has ALREADY been issued to a live player's Challenges or
// TriggerState. Derived ids (grove_quest_ids.ts) are used only for keys absent
// from this table, so no in-flight player loses progress to the migration.
//
// DO NOT EDIT AN EXISTING ROW. Adding a row is a migration; changing one
// orphans player state. grove_quest_ids.test.ts enforces both.

/** questId -> native challenge id. ${quest.length} entries. */
export const GROVE_QUEST_ID_PINS: Readonly<Record<string, number>> =
  Object.freeze({
${render(quest)}
  });

/**
 * Trigger-node pins, keyed by the manifest's semantic path:
 *   "<questId>:root"                  the seq root
 *   "<questId>:objective:<stepId>"    one objective leaf
 *   "<questId>:unlock:root"           the unlock node
 *   "<questId>:unlock:<prereqQuestId>" one prerequisite leaf
 * ${step.length} entries.
 */
export const GROVE_STEP_ID_PINS: Readonly<Record<string, number>> =
  Object.freeze({
${render(step)}
  });
`
  );

  console.log(
    "wrote %s\n  %d quest pins, %d trigger-node pins",
    path.relative(ROOT, OUT),
    quest.length,
    step.length
  );
}

main();
